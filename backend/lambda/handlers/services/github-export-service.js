/**
 * Generates GitHub CLI script for automated issue creation
 * @param {Object} planData - Complete plan data from DynamoDB
 * @param {string} repoName - Target GitHub repository (owner/repo)
 * @returns {string} GitHub CLI script content
 */
function generateGitHubCLIScript(planData, repoName) {
  let script = `#!/bin/bash
# GitHub CLI Script for Bulk Issue Creation
# Generated by Color Code Research Hub
# Repository: ${repoName}
# Generated: ${new Date().toISOString()}

set -e  # Exit on any error

echo "🚀 Creating milestones and issues for ${repoName}"
echo "📋 Total phases: ${planData.phases?.length || 0}"

# Check if gh CLI is installed and authenticated
if ! command -v gh &> /dev/null; then
    echo "❌ GitHub CLI (gh) is not installed"
    echo "📖 Install from: https://cli.github.com/"
    exit 1
fi

if ! gh auth status &> /dev/null; then
    echo "❌ GitHub CLI is not authenticated"
    echo "📖 Run: gh auth login"
    exit 1
fi

echo "✅ GitHub CLI is ready"
echo ""

# Create milestones
echo "📍 Creating milestones..."
`;

  // Add milestone creation
  if (planData.phases) {
    planData.phases.forEach((phase, index) => {
      const description = phase.description?.replace(/"/g, '\\"') || '';
      script += `
echo "Creating milestone: ${phase.title}"
gh issue milestone create "${phase.title}" --description "${description}" --repo ${repoName} || echo "⚠️  Milestone may already exist"
`;
    });
  }

  script += `
echo ""
echo "📝 Creating issues for first phase (Landing Page)..."
`;

  // Add issue creation for first phase only
  const firstPhase = planData.phases?.[0];
  if (firstPhase?.issues) {
    firstPhase.issues.forEach((issue, index) => {
      const title = issue.title?.replace(/"/g, '\\"') || `Issue ${index + 1}`;
      const description = issue.description?.replace(/"/g, '\\"') || '';
      const labels = ['auto-generated', firstPhase.id];
      
      script += `
echo "Creating issue: ${title}"
gh issue create \\
  --title "${title}" \\
  --body "${description}" \\
  --milestone "${firstPhase.title}" \\
  --label "${labels.join(',')}" \\
  --repo ${repoName}
`;
    });
  }

  script += `
echo ""
echo "✅ Bulk upload completed!"
echo "📊 Visit: https://github.com/${repoName}/issues"
echo "📈 Visit: https://github.com/${repoName}/milestones"
`;

  return script;
}

/**
 * Generates CSV file for GitHub import tools
 * @param {Object} planData - Complete plan data from DynamoDB
 * @returns {string} CSV content
 */
function generateCSVExport(planData) {
  let csv = 'Type,Title,Description,Milestone,Labels,Assignee,Priority\n';
  
  // Add milestones
  if (planData.phases) {
    planData.phases.forEach(phase => {
      const description = (phase.description || '').replace(/"/g, '""');
      csv += `milestone,"${phase.title}","${description}",,,,\n`;
    });
  }
  
  // Add issues for first phase
  const firstPhase = planData.phases?.[0];
  if (firstPhase?.issues) {
    firstPhase.issues.forEach(issue => {
      const title = (issue.title || '').replace(/"/g, '""');
      const description = (issue.description || '').replace(/"/g, '""');
      const labels = ['auto-generated', firstPhase.id].join(';');
      const priority = issue.priority || 'medium';
      
      csv += `issue,"${title}","${description}","${firstPhase.title}","${labels}","${issue.assignee || ''}","${priority}"\n`;
    });
  }
  
  return csv;
}

/**
 * Generates JSON export for custom tools
 * @param {Object} planData - Complete plan data from DynamoDB
 * @param {string} repoName - Target repository
 * @returns {string} JSON content
 */
function generateJSONExport(planData, repoName) {
  const exportData = {
    repository: repoName,
    generatedAt: new Date().toISOString(),
    generator: 'Color Code Research Hub',
    milestones: planData.phases?.map(phase => ({
      title: phase.title,
      description: phase.description,
      state: 'open'
    })) || [],
    issues: [],
    summary: {
      totalPhases: planData.phases?.length || 0,
      totalEpics: planData.phases?.reduce((total, phase) => total + (phase.epics?.length || 0), 0) || 0,
      totalIssues: planData.phases?.reduce((total, phase) => total + (phase.issues?.length || 0), 0) || 0,
      firstPhaseIssues: planData.phases?.[0]?.issues?.length || 0
    }
  };
  
  // Add issues for first phase
  const firstPhase = planData.phases?.[0];
  if (firstPhase?.issues) {
    exportData.issues = firstPhase.issues.map(issue => ({
      title: issue.title,
      body: issue.description,
      milestone: firstPhase.title,
      labels: ['auto-generated', firstPhase.id],
      assignee: issue.assignee || null,
      priority: issue.priority || 'medium',
      estimatedHours: issue.estimatedHours || 8
    }));
  }
  
  return JSON.stringify(exportData, null, 2);
}

/**
 * Generates Markdown documentation
 * @param {Object} planData - Complete plan data from DynamoDB
 * @param {string} repoName - Target repository
 * @returns {string} Markdown content
 */
function generateMarkdownExport(planData, repoName) {
  let markdown = `# Project Plan Export\n\n`;
  markdown += `**Repository:** ${repoName}\n`;
  markdown += `**Generated:** ${new Date().toLocaleString()}\n`;
  markdown += `**Source:** Color Code Research Hub\n\n`;
  
  markdown += `## 📊 Summary\n\n`;
  markdown += `- **Total Phases:** ${planData.phases?.length || 0}\n`;
  markdown += `- **Total Epics:** ${planData.phases?.reduce((total, phase) => total + (phase.epics?.length || 0), 0) || 0}\n`;
  markdown += `- **Total Issues:** ${planData.phases?.reduce((total, phase) => total + (phase.issues?.length || 0), 0) || 0}\n`;
  markdown += `- **First Phase Issues:** ${planData.phases?.[0]?.issues?.length || 0} (included in export)\n\n`;
  
  markdown += `## 🎯 Milestones\n\n`;
  if (planData.phases) {
    planData.phases.forEach((phase, index) => {
      markdown += `### ${index + 1}. ${phase.title}\n\n`;
      markdown += `${phase.description}\n\n`;
      if (phase.suggestedRoles) {
        markdown += `**Suggested Roles:** ${phase.suggestedRoles.join(', ')}\n\n`;
      }
    });
  }
  
  markdown += `## 📝 Issues (First Phase Only)\n\n`;
  const firstPhase = planData.phases?.[0];
  if (firstPhase?.issues) {
    firstPhase.issues.forEach((issue, index) => {
      markdown += `### Issue ${index + 1}: ${issue.title}\n\n`;
      markdown += `**Description:** ${issue.description}\n\n`;
      markdown += `**Assignee:** ${issue.assignee || 'Unassigned'}\n`;
      markdown += `**Priority:** ${issue.priority || 'Medium'}\n`;
      markdown += `**Estimated Hours:** ${issue.estimatedHours || 8}\n\n`;
      markdown += `---\n\n`;
    });
  }
  
  return markdown;
}

